import streamlit as st
import pandas as pd
import joblib

#Load the trained model
loaded_model = joblib.load('models/Loan_Approval_Prediction_model.pkl')

#app
st.title('🏦 Loan Approval Predictor')
st.write('Enter the Applicants details below to predict the Loan Approval.')
st.info("This prediction is generated by a trained Random Forest machine learning model.")

# Applicant details
st.subheader("👤 Applicant Information")

col1, col2 = st.columns(2)

with col1:
    gender = st.selectbox(
        "Gender",
        ["Male", "Female"]
    )

with col2:
    married = st.selectbox(
        "Married",
        ["No", "Yes"]
    )

col1, col2 = st.columns(2)

with col1:
    dependents = st.selectbox(
        "Dependents",
        [0, 1, 2, 3]
    )
with col2:
    education = st.selectbox(
        "Education",
        ["Graduate", "Not Graduate"]
    )

self_employed = st.selectbox(
    "Self Employed",
    ["No", "Yes"]
)

st.subheader("💰 Financial Information")

col1, col2 = st.columns(2)

with col1:
    applicant_income = st.number_input(
        "Applicant Income",
        min_value=0,
        value=5000
    )
with col2:
    coapplicant_income = st.number_input(
        "Coapplicant Income",
        min_value=0,
        value=0
    )

col1, col2 = st.columns(2)

with col1:
    loan_amount = st.number_input(
        "Loan Amount",
        min_value=0,
        value=150
    )

with col2:
    loan_amount_term = st.number_input(
        "Loan Amount Term (in months)",
        min_value=0,
        value=360
    )

st.subheader("🏠 Loan Information")

col1, col2 = st.columns(2)

with col1:
    credit_history = st.selectbox(
        "Credit History",
        [0, 1]
    )

with col2:
    property_area = st.selectbox(
        "Property Area",
        ["Rural", "Semiurban", "Urban"]
    )

# Convert categorical values into numbers

gender = 0 if gender == "Male" else 1

married = 1 if married == "Yes" else 0

education = 1 if education == "Graduate" else 0

self_employed = 1 if self_employed == "Yes" else 0

property_area = {
    "Rural": 0,
    "Semiurban": 1,
    "Urban": 2
}[property_area]

if st.button("Predict Loan Approval"):

    new_applicant = pd.DataFrame({
        "Gender": [gender],
        "Married": [married],
        "Dependents": [dependents],
        "Education": [education],
        "Self_Employed": [self_employed],
        "ApplicantIncome": [applicant_income],
        "CoapplicantIncome": [coapplicant_income],
        "LoanAmount": [loan_amount],
        "Loan_Amount_Term": [loan_amount_term],
        "Credit_History": [credit_history],
        "Property_Area": [property_area]
    })

    

    prediction = loaded_model.predict(new_applicant)

    if prediction[0] == 1:
        st.success("✅ Loan Approved!")
    else:
        st.error("❌ Loan Rejected!")

